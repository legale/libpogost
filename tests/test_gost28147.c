#include <libpogost/gost28147.h>

#include <stdio.h>
#include <string.h>

static const uint8_t key[32] = {
  0xbb, 0xf1, 0xed, 0xd3, 0x20, 0xaf, 0x8a, 0x62,
  0x8e, 0x11, 0xc8, 0xa9, 0x51, 0xcc, 0xbe, 0x81,
  0x47, 0x7b, 0x41, 0xa1, 0x6a, 0xf6, 0x7f, 0x05,
  0xe8, 0x51, 0x2f, 0x9e, 0x01, 0xf8, 0xcf, 0x49,
};

static const uint8_t plain[16] = {
  0x74, 0x3d, 0x76, 0xf9, 0x1b, 0xee, 0x35, 0x3c,
  0xa2, 0x5c, 0x3b, 0x10, 0xeb, 0x64, 0xcf, 0xf5,
};

static const uint8_t cipher[16] = {
  0xc3, 0x73, 0x90, 0x95, 0x35, 0x58, 0x08, 0x63,
  0xcb, 0x68, 0x85, 0x96, 0x77, 0xe8, 0xfb, 0xa9,
};

int main(void)
{
  struct gost28147_ctx ctx;
  uint8_t buf[16];

  if (gost28147_setkey_cryptopro_a(&ctx, key))
    return 1;
  gost28147_encrypt(&ctx, buf, plain);
  gost28147_encrypt(&ctx, buf + 8, plain + 8);
  if (memcmp(buf, cipher, sizeof(buf))) {
    fprintf(stderr, "gost28147 encrypt vector failed\n");
    return 1;
  }
  gost28147_decrypt(&ctx, buf, cipher);
  gost28147_decrypt(&ctx, buf + 8, cipher + 8);
  if (memcmp(buf, plain, sizeof(buf))) {
    fprintf(stderr, "gost28147 decrypt vector failed\n");
    return 1;
  }

  puts("gost28147: ok");
  return 0;
}
