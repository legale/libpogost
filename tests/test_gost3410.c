static int unhex(u8 *out, size_t out_len, const char *hex)
{
  unsigned int value;
  size_t i;

  if (strlen(hex) != out_len * 2)
    return -1;
  for (i = 0; i < out_len; i++) {
    if (sscanf(hex + i * 2, "%2x", &value) != 1)
      return -1;
    out[i] = value;
  }
  return 0;
}

int main(int argc, char **argv)
{
  u8 bad_signature[sizeof(signature)];
  u8 private_key[GOST3410_512_KEY_SIZE] = { 3 };
  u8 nonce[GOST3410_512_KEY_SIZE] = { 2 };
  u8 generated_public[GOST3410_512_PUBLIC_SIZE];
  u8 generated_signature[GOST3410_512_SIGNATURE_SIZE];

  if (argc == 2) {
    if (unhex(private_key, sizeof(private_key), argv[1]) ||
        gost3410_512a_public(generated_public, private_key))
      return 2;
    for (size_t i = 0; i < sizeof(generated_public); i++)
      printf("%02x", generated_public[i]);
    putchar('\n');
    return 0;
  }

  if (argc == 4) {
    u8 pub[sizeof(public_key)];
    u8 hash[sizeof(digest)];
    u8 sig[sizeof(signature)];

    if (unhex(pub, sizeof(pub), argv[1]) ||
        unhex(hash, sizeof(hash), argv[2]) ||
        unhex(sig, sizeof(sig), argv[3]))
      return 2;
    return gost3410_512a_verify(pub, hash, sig) ? 1 : 0;
  }

  if (test_256()) {
    fputs("gost3410 256 CryptoPro XchA test failed\n", stderr);
    return 1;
  }
  if (test_tc26_256()) {
    fputs("gost3410 256 TC26 paramSetA test failed\n", stderr);
    return 1;
  }

  if (gost3410_512a_verify(public_key, digest, signature))
    return 1;
  memcpy(bad_signature, signature, sizeof(signature));
  bad_signature[0] ^= 1;
  if (!gost3410_512a_verify(public_key, digest, bad_signature))
    return 1;
  if (gost3410_512a_public(generated_public, private_key)) {
    fputs("public generation failed\n", stderr);
    return 1;
  }
  if (gost3410_512a_sign(generated_signature, digest, private_key, nonce)) {
    fputs("signing failed\n", stderr);
    return 1;
  }
  if (gost3410_512a_verify(generated_public, digest, generated_signature)) {
    fputs("generated signature verification failed\n", stderr);
    return 1;
  }
  puts("gost3410 512 paramSetA verify: PASS");
  return 0;
}
