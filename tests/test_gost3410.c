static int unhex(uint8_t *out, size_t out_len, const char *hex)
{
  unsigned int value;
  size_t i;

  if (strlen(hex) != out_len * 2)
    return -1;
  for (i = 0; i < out_len; i++) {
    if (sscanf(hex + i * 2, "%2x", &value) != 1)
      return -1;
    out[i] = value;
  }
  return 0;
}

