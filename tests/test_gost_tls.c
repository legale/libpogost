static int test_tls13_ecdh(void)
{
  const u8 priv_client[32] = {
    0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08,
    0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18,
    0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27, 0x28,
    0x31, 0x32, 0x33, 0x34, 0x35, 0x36, 0x37, 0x38
  };
  const u8 priv_server[32] = {
    0x41, 0x42, 0x43, 0x44, 0x45, 0x46, 0x47, 0x48,
    0x51, 0x52, 0x53, 0x54, 0x55, 0x56, 0x57, 0x58,
    0x61, 0x62, 0x63, 0x64, 0x65, 0x66, 0x67, 0x68,
    0x71, 0x72, 0x73, 0x74, 0x75, 0x76, 0x77, 0x08
  };
  u8 pub_client[64];
  u8 pub_server[64];
  u8 shared_client[32];
  u8 shared_server[32];
  u8 zero[32] = { 0 };

  if (gost3410_256tc26a_public(pub_client, priv_client) != 0) {
    fprintf(stderr, "FAIL: gost3410_256tc26a_public(client)\n");
    return 1;
  }
  if (gost3410_256tc26a_public(pub_server, priv_server) != 0) {
    fprintf(stderr, "FAIL: gost3410_256tc26a_public(server)\n");
    return 1;
  }
  if (gost3410_256tc26a_ecdh(shared_client, pub_server, priv_client) != 0) {
    fprintf(stderr, "FAIL: gost3410_256tc26a_ecdh(client)\n");
    return 1;
  }
  if (gost3410_256tc26a_ecdh(shared_server, pub_client, priv_server) != 0) {
    fprintf(stderr, "FAIL: gost3410_256tc26a_ecdh(server)\n");
    return 1;
  }
  if (memcmp(shared_client, shared_server, 32) != 0) {
    fprintf(stderr, "FAIL: shared_client != shared_server\n");
    return 1;
  }
  if (memcmp(shared_client, zero, 32) == 0) {
    fprintf(stderr, "FAIL: shared secret is all zero\n");
    return 1;
  }
  pub_server[0] ^= 0x01;
  if (gost3410_256tc26a_ecdh(shared_client, pub_server, priv_client) == 0) {
    fprintf(stderr, "FAIL: corrupted public key accepted\n");
    return 1;
  }
  return 0;
}

int main(void)
{
  int ret = 0;

  ret |= test_tls12_primitives();
  ret |= test_tls13_mgm();
  ret |= test_tls13_nonce();
  ret |= test_tls13_tlstree();
  ret |= test_tls13_hkdf();
  ret |= test_tls13_ecdh();

  if (ret == 0)
    printf("test_gost_tls: all TLS 1.2 and TLS 1.3 primitives PASSED\n");

  return ret;
}
