#include <stdio.h>
#include <string.h>

#include <libpogost/kuznechik.h>

/* Вектор из тестов Linux Crypto API. */
static const unsigned char key[KUZNECHIK_KEY_SIZE] = {
  0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff,
  0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77,
  0xfe, 0xdc, 0xba, 0x98, 0x76, 0x54, 0x32, 0x10,
  0x01, 0x23, 0x45, 0x67, 0x89, 0xab, 0xcd, 0xef,
};

static const unsigned char plaintext[KUZNECHIK_BLOCK_SIZE] = {
  0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x00,
  0xff, 0xee, 0xdd, 0xcc, 0xbb, 0xaa, 0x99, 0x88,
};

static const unsigned char ciphertext[KUZNECHIK_BLOCK_SIZE] = {
  0x7f, 0x67, 0x9d, 0x90, 0xbe, 0xbc, 0x24, 0x30,
  0x5a, 0x46, 0x8d, 0x42, 0xb9, 0xd4, 0xed, 0xcd,
};

int main(void)
{
  struct kuznechik_ctx ctx;
  unsigned char out[KUZNECHIK_BLOCK_SIZE];
  unsigned char recovered[KUZNECHIK_BLOCK_SIZE];

  if (kuznechik_setkey(&ctx, key))
    return 1;
  kuznechik_encrypt(&ctx, out, plaintext);
  if (memcmp(out, ciphertext, sizeof(out)))
    return 1;
  kuznechik_decrypt(&ctx, recovered, out);
  if (memcmp(recovered, plaintext, sizeof(recovered)))
    return 1;
  puts("kuznechik generic: PASS");
  return 0;
}
