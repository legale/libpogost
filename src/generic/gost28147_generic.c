static u32 get_le32(const u8 in[4])
{
  return (u32)in[0] | (u32)in[1] << 8 |
         (u32)in[2] << 16 | (u32)in[3] << 24;
}

static void put_le32(u8 out[4], u32 v)
{
  out[0] = v;
  out[1] = v >> 8;
  out[2] = v >> 16;
  out[3] = v >> 24;
}

static u32 subst(const struct gost28147_state *st, u32 v)
{
  u32 x = 0;
  unsigned int i;

  for (i = 0; i < 8; i++) {
    x |= (u32)st->sbox[7 - i][(v >> (i * 4)) & 0xf] << (i * 4);
  }
  return x << 11 | x >> 21;
}

static void crypt(const struct gost28147_state *st, u8 out[8],
                  const u8 in[8], int dec)
{
  u32 n1 = get_le32(in);
  u32 n2 = get_le32(in + 4);
  unsigned int r;

  for (r = 0; r < 32; r++) {
    unsigned int k;

    if (!dec) {
      k = r < 24 ? r & 7 : 7 - (r & 7);
    } else {
      k = r < 8 ? r : 7 - (r & 7);
    }

    if (r & 1) {
      n1 ^= subst(st, n2 + st->key[k]);
    } else {
      n2 ^= subst(st, n1 + st->key[k]);
    }
  }

  put_le32(out, n2);
  put_le32(out + 4, n1);
}


static const u8 key_mesh_key[32] = {
  0x69, 0x00, 0x72, 0x22, 0x64, 0xc9, 0x04, 0x23,
  0x8d, 0x3a, 0xdb, 0x96, 0x46, 0xe9, 0x2a, 0xc4,
  0x18, 0xfe, 0xac, 0x94, 0x00, 0xed, 0x07, 0x12,
  0xc0, 0x86, 0xdc, 0xc2, 0xef, 0x4c, 0xa9, 0x2b,
};

static void key_mesh(struct gost28147_state *st, u8 iv[8])
{
  u8 key[32];
  u8 next_iv[8];
  const u8 (*sbox)[16] = st->sbox;
  unsigned int i;

  for (i = 0; i < 4; i++) {
    gost28147_decrypt_raw(st, key + i * 8, key_mesh_key + i * 8);
  }
  gost28147_setkey_raw(st, key, sbox);
  gost28147_encrypt_raw(st, next_iv, iv);
  memcpy(iv, next_iv, sizeof(next_iv));
  memset(key, 0, sizeof(key));
  memset(next_iv, 0, sizeof(next_iv));
}

int gost28147_cfb_crypt(struct gost28147_state *st, u8 *out,
                        const u8 *in, size_t len, const u8 iv[8],
                        int enc, int mesh)
{
  u8 cur_iv[8];
  u8 gamma[8];
  size_t off = 0;

  if (!st || !out || (!in && len) || !iv) {
    return -1;
  }

  memcpy(cur_iv, iv, sizeof(cur_iv));
  while (off < len) {
    size_t n = len - off;
    size_t i;

    if (mesh && off && !(off % 1024)) {
      key_mesh(st, cur_iv);
    }
    if (n > sizeof(gamma)) {
      n = sizeof(gamma);
    }
    gost28147_encrypt_raw(st, gamma, cur_iv);
    for (i = 0; i < n; i++) {
      u8 c = in[off + i] ^ gamma[i];

      out[off + i] = c;
      cur_iv[i] = enc ? c : in[off + i];
    }
    off += n;
  }

  memset(cur_iv, 0, sizeof(cur_iv));
  memset(gamma, 0, sizeof(gamma));
  return 0;
}

void gost28147_setkey_raw(struct gost28147_state *st, const u8 key[32],
                          const u8 sbox[8][16])
{
  unsigned int i;

  for (i = 0; i < 8; i++) {
    st->key[i] = get_le32(key + i * 4);
  }
  st->sbox = sbox;
}

void gost28147_encrypt_raw(const struct gost28147_state *st, u8 out[8],
                           const u8 in[8])
{
  crypt(st, out, in, 0);
}

void gost28147_decrypt_raw(const struct gost28147_state *st, u8 out[8],
                           const u8 in[8])
{
  crypt(st, out, in, 1);
}

int gost28147_mac4_raw(const struct gost28147_state *st, u8 out[4],
                       const u8 iv[8], const u8 *in, size_t len)
{
  u8 mac[8];
  size_t off;

  if (!st || !out || !iv || !in || !len || len % 8) {
    return -1;
  }

  memcpy(mac, iv, sizeof(mac));
  for (off = 0; off < len; off += 8) {
    u32 n1 = get_le32(mac) ^ get_le32(in + off);
    u32 n2 = get_le32(mac + 4) ^ get_le32(in + off + 4);
    unsigned int r;

    for (r = 0; r < 16; r++) {
      if (r & 1) {
        n1 ^= subst(st, n2 + st->key[r & 7]);
      } else {
        n2 ^= subst(st, n1 + st->key[r & 7]);
      }
    }
    put_le32(mac, n1);
    put_le32(mac + 4, n2);
  }
  memcpy(out, mac, 4);
  memset(mac, 0, sizeof(mac));
  return 0;
}

static struct gost28147_state *state(struct gost28147_ctx *ctx)
{
  return (struct gost28147_state *)ctx;
}

static const struct gost28147_state *state_const(const struct gost28147_ctx *ctx)
{
  return (const struct gost28147_state *)ctx;
}

_Static_assert(sizeof(struct gost28147_state) <= sizeof(struct gost28147_ctx),
               "GOST28147_CTX_SIZE is too small");

int gost28147_setkey_cryptopro_a(struct gost28147_ctx *ctx,
                                 const u8 key[32])
{
  if (!ctx || !key) {
    return -1;
  }
  gost28147_setkey_raw(state(ctx), key, gost28147_sbox_cryptopro_a);
  return 0;
}

void gost28147_encrypt(const struct gost28147_ctx *ctx, u8 out[8],
                       const u8 in[8])
{
  gost28147_encrypt_raw(state_const(ctx), out, in);
}

void gost28147_decrypt(const struct gost28147_ctx *ctx, u8 out[8],
                       const u8 in[8])
{
  gost28147_decrypt_raw(state_const(ctx), out, in);
}
